"""Solver 기준 실행에 사용하는 15×15 고정 미로."""

import numpy as np

from core.maze import EMPTY, WALL


_LAYOUT = (
    "...............",
    "..###...#......",
    "....#...#..###.",
    ".#..#......#...",
    ".#.....###.#...",
    ".####......#...",
    "......#....#...",
    "..#...#.#####..",
    "..#........#...",
    "..#####....#...",
    "........#......",
    ".###....#.####.",
    "...#....#......",
    "...#..###..##..",
    "...............",
)


def get_fixed_grid():
    """입력 없이 초기 벽 배치를 담은 독립적인 정수 격자를 반환한다."""
    return np.array(
        [[WALL if cell == "#" else EMPTY for cell in row] for row in _LAYOUT],
        dtype=int,
    )
